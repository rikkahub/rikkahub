internal object PdfEncodings {
    private val glyphList: Map<String, String> by lazy { loadGlyphList("glyphlist.txt") }
    private val texGlyphList: Map<String, String> by lazy { loadGlyphList("texglyphs.txt") }

    // cmex 等 TeX 字体里同一符号不同尺寸的后缀，如 parenleftbig、summationdisplay、hatwide
    private val texSizeSuffix = Regex("(big|Big|bigg|Bigg|text|display|wide|wider|widest)$")

    fun byName(name: String): CharArray? = when (name) {
        "StandardEncoding" -> STANDARD
        "WinAnsiEncoding" -> WIN_ANSI
        "MacRomanEncoding" -> MAC_ROMAN
        "PDFDocEncoding" -> PDF_DOC
        else -> null
    }

    /**
     * 按 AGL 规范把字形名转换为 Unicode：去掉 `.` 后缀，`_` 连接的连字逐个转换，
     * 支持 uniXXXX 与 uXXXX[XX] 形式。无法识别时返回 null。
     */
    fun glyphToUnicode(name: String): String? {
        glyphList[name]?.let { return it }
        val base = name.substringBefore('.')
        if (base.isEmpty()) return null
        if (base != name) glyphList[base]?.let { return it }
        if ('_' in base) {
            val parts = base.split('_').map { glyphComponent(it) ?: return null }
            return parts.joinToString("")
        }
        return glyphComponent(base) ?: texGlyph(base)
    }

    /** AGL 无法识别时按 TeX 字体的字形名再查一次 */
    private fun texGlyph(name: String): String? {
        texGlyphList[name]?.let { return it }
        val stripped = name.replace(texSizeSuffix, "")
        if (stripped == name || stripped.isEmpty()) return null
        return glyphList[stripped] ?: texGlyphList[stripped]
    }

    private fun glyphComponent(name: String): String? {
        glyphList[name]?.let { return it }
        if (name.startsWith("uni") && name.length >= 7 && (name.length - 3) % 4 == 0) {
            val sb = StringBuilder()
            var i = 3
            while (i < name.length) {
                val cp = name.substring(i, i + 4).toIntOrNull(16) ?: return null
                if (cp in 0xD800..0xDFFF) return null
                sb.append(cp.toChar())
                i += 4
            }
            return sb.toString()
        }
        if (name.startsWith("u") && name.length in 5..7) {
            val cp = name.substring(1).toIntOrNull(16) ?: return null
            if (cp in 0xD800..0xDFFF || cp > 0x10FFFF) return null
            return String(Character.toChars(cp))
        }
        return null
    }

    fun decodeTextString(bytes: ByteArray): String {
        if (bytes.size >= 2 && bytes[0] == 0xFE.toByte() && bytes[1] == 0xFF.toByte()) {
            return String(bytes, 2, bytes.size - 2, Charsets.UTF_16BE)
        }
        if (bytes.size >= 3 && bytes[0] == 0xEF.toByte() && bytes[1] == 0xBB.toByte() && bytes[2] == 0xBF.toByte()) {
            return String(bytes, 3, bytes.size - 3, Charsets.UTF_8)
        }
        val sb = StringBuilder(bytes.size)
        for (b in bytes) {
            val c = PDF_DOC[b.toInt() and 0xFF]
            if (c != '\u0000') sb.append(c)
        }
        return sb.toString()
    }

    private fun loadGlyphList(file: String): Map<String, String> {
        val map = HashMap<String, String>()
        val stream = PdfEncodings::class.java.getResourceAsStream("$RESOURCE_DIR/$file") ?: return map
        stream.bufferedReader().useLines { lines ->
            for (line in lines) {
                if (line.isEmpty() || line[0] == '#') continue
                val sep = line.indexOf(';')
                if (sep <= 0) continue
                val value = line.substring(sep + 1).split(' ').joinToString("") { hex ->
                    String(Character.toChars(hex.toInt(16)))
                }
                map[line.substring(0, sep)] = value
            }
        }
        return map
    }

